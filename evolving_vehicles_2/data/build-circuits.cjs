/* Rebuild the offline browser bundle from vendored GeoJSON datasets.
 * f1-circuits originals are MIT; the separate OpenStreetMap subset is ODbL 1.0.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { densify } = require('./circuit-geometry.cjs');

const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, 'manifest.json'), 'utf8'));
const circuits = manifest.circuits.map(({ file, sourceProfile = 'f1-circuits', ...metadata }) => {
  const raw = JSON.parse(fs.readFileSync(path.join(__dirname, file), 'utf8'));
  const geometry = raw.type === 'Feature' ? raw.geometry : raw.features[0].geometry;
  if (geometry.type !== 'LineString') throw new Error(`${file}: expected LineString`);
  const sourceCoordinates = geometry.coordinates.map(point => point.slice(0, 2));
  let coordinates = sourceCoordinates;
  if (coordinates.length < 3 || coordinates.some(point => point.length !== 2 || !point.every(Number.isFinite) || Math.abs(point[0]) > 180 || Math.abs(point[1]) > 90)) {
    throw new Error(`${file}: invalid coordinates`);
  }
  const first = coordinates[0];
  const last = coordinates[coordinates.length - 1];
  // Reject open paths: closing an arbitrary OSM way can invent a nonexistent road.
  if (first[0] !== last[0] || first[1] !== last[1]) throw new Error(`${file}: source path must be closed`);
  const osm = sourceProfile === 'openstreetmap';
  if (osm && !metadata.sourceUrl) throw new Error(`${file}: missing OpenStreetMap source URL`);
  if (!Number.isFinite(metadata.lengthM) || metadata.lengthM <= 100) throw new Error(`${file}: invalid lengthM`);
  let elevation = {};
  if (metadata.elevationFile) {
    const stored = JSON.parse(fs.readFileSync(path.join(__dirname, metadata.elevationFile), 'utf8'));
    if (stored.sourceCoordinateHash !== crypto.createHash('sha256').update(JSON.stringify(sourceCoordinates)).digest('hex')) throw new Error(`${file}: changed source geometry needs refreshed elevation samples`);
    coordinates = densify(sourceCoordinates, stored.metadata.elevationSamplingMaxSpacingM);
    const hash = crypto.createHash('sha256').update(JSON.stringify(coordinates)).digest('hex');
    if (stored.coordinateHash !== hash || JSON.stringify(stored.coordinates) !== JSON.stringify(coordinates) || stored.elevations.length !== coordinates.length || stored.elevations.some(z => !Number.isFinite(z))) {
      throw new Error(`${file}: elevation data does not match its coordinates`);
    }
    if (stored.elevations[0] !== stored.elevations.at(-1)) throw new Error(`${file}: elevation seam is not closed`);
    elevation = { ...stored.metadata, elevations: stored.elevations };
  }
  return {
    sourceProfile,
    sourceUrl: osm ? metadata.sourceUrl : `${manifest.repository}/blob/${manifest.revision}/circuits/${file}`,
    sourceName: osm ? 'OpenStreetMap' : 'bacinger/f1-circuits',
    author: osm ? 'OpenStreetMap contributors' : manifest.author,
    attribution: osm ? '© OpenStreetMap contributors' : '© Tomislav Bacinger',
    license: osm ? 'ODbL 1.0' : manifest.license,
    licenseUrl: osm ? 'https://opendatacommons.org/licenses/odbl/1-0/' : `${manifest.repository}/blob/${manifest.revision}/LICENSE.md`,
    licenseFile: osm ? 'data/LICENSE.ODbL-1.0.txt' : 'data/LICENSE.f1-circuits.txt',
    sourceRevision: osm ? undefined : manifest.revision,
    retrievedOn: manifest.retrievedOn,
    startNote: '원본 좌표의 시작점·진행 순서를 사용합니다. 실제 경기의 출발선 위치와 일치하지 않을 수 있습니다.',
    lengthKind: 'official',
    localDataUrl: `data/${file}`,
    ...metadata,
    ...elevation,
    sourcePointCount: sourceCoordinates.length,
    coordinates,
  };
});

const notice = `/*
 * Circuit data collection: each record carries its source and license.
 * International f1-circuits subset: (c) 2019-2025 Tomislav Bacinger, MIT.
 * ${manifest.repository}, revision ${manifest.revision}.
 * Korean OpenStreetMap subset: (c) OpenStreetMap contributors, ODbL 1.0.
 * https://www.openstreetmap.org/copyright
 * https://opendatacommons.org/licenses/odbl/1-0/
 * Full licenses: data/LICENSE.f1-circuits.txt and data/LICENSE.ODbL-1.0.txt.
 * Provenance, raw data and derivation details: SOURCES.md and data/kr-osm/.
 * Generated by node evolving_vehicles_2/data/build-circuits.cjs.
 * Original vertices are preserved; long segments gain collinear <=75m samples.
 * Elevation: Open-Meteo / Copernicus DEM GLO-90 (2021), European Union and ESA.
 * Exact requests, responses and attribution are in data/elevation/.
 * No network is needed by the browser.
 */\n`;
const body = `(function (root) {\n  'use strict';\n  const circuits = ${JSON.stringify(circuits, null, 2)};\n  if (typeof module === 'object' && module.exports) module.exports = circuits;\n  if (root) root.RaceCircuits = circuits;\n})(typeof window !== 'undefined' ? window : globalThis);\n`;
fs.writeFileSync(path.join(__dirname, '..', 'circuits.js'), notice + body);
for (const circuit of circuits) console.log(`${circuit.id}: ${circuit.coordinates.length} coordinates, ${circuit.lengthM} m`);
