// Housing configuration and actual monthly charges in a mobile Chromium page.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {createRequire}=require('node:module');
let playwright;
try{playwright=require('playwright');}catch{playwright=createRequire(path.join(process.env.USERPROFILE||process.env.HOME,'.codex/skills/develop-web-game/package.json'))('playwright');}
const base=(process.env.WEBSIM_URL||'http://127.0.0.1:8766').replace(/\/$/,'');
const output=path.resolve(process.env.WEBSIM_EVIDENCE||'output/playwright/weekend-season2-housing');
fs.mkdirSync(output,{recursive:true});

(async()=>{
  const browser=await playwright.chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,reducedMotion:'reduce'});
  const errors=[],checks=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  const state=()=>page.evaluate(()=>JSON.parse(render_game_to_text()));
  const saved=()=>page.evaluate(()=>S2Storage.load());
  const pass=message=>{checks.push(message);console.log('PASS',message);};
  try{
    await page.goto(base+'/weekend_season2/index.html');
    const start=await page.locator('#start-btn').boundingBox();
    assert.ok(start.y+start.height<=844,'first-screen start remains visible');
    assert.ok(await page.locator('.life-housing').isVisible());
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollHeight)<1350);
    await page.screenshot({path:path.join(output,'housing-life-mobile.png'),fullPage:true});
    await page.locator('#advanced-settings>summary').click();
    await page.locator('[data-preset=worker]').click();
    await page.locator('[name=housing]').selectOption('apartment');
    const tenure=page.locator('[name=housingTenure]');
    await tenure.selectOption('own');
    await tenure.focus();
    await tenure.press('ArrowDown');
    assert.equal(await tenure.inputValue(),'rent','keyboard changes the tenancy');
    await page.locator('[name=monthlyRent]').fill('75.1234');
    await page.locator('[name=housingLoanPrincipal]').fill('10000.0001');
    await page.locator('[name=housingLoanRateBps]').fill('4.37');
    await page.locator('[name=fixedCosts]').fill('100');
    let current=await state();
    assert.equal(current.housing.rent,751000);
    assert.equal(current.housing.loanPrincipal,100000000);
    assert.equal(current.housing.rateBps,437);
    assert.equal(current.housing.interest,364167);
    assert.equal(current.housing.monthly.total,2115167);
    assert.match(await page.locator('#housing-preview').innerText(),/생활비까지 매달 211.5만원/);
    assert.match(await page.locator('[name=fixedCosts]').locator('..').innerText(),/주거비를 뺀 생활비/);
    assert.match(await page.locator('.scene-caption').innerText(),/아파트 · 월세/);
    await page.locator('[name=housingLoanRateBps]').fill('31');
    assert.match(await page.locator('#housing-preview').innerText(),/0~30%/);
    assert.equal(await page.locator('[name=housingLoanRateBps]').evaluate(e=>e.validity.valid),false);
    await page.locator('[name=housingLoanRateBps]').fill('4.37');
    await tenure.selectOption('jeonse');
    assert.equal(await page.locator('[name=monthlyRent]').isVisible(),false);
    assert.equal((await state()).housing.rent,0);
    assert.equal((await state()).housing.interest,364167);
    await tenure.selectOption('own');
    assert.equal((await state()).housing.interest,364167,'ownership can also have a housing loan');
    assert.match(await page.locator('.scene-caption').innerText(),/아파트 · 자가/);
    await tenure.selectOption('rent');
    await page.locator('[name=monthlyRent]').fill('75.1234');
    await page.locator('#housing-settings').screenshot({path:path.join(output,'housing-settings.png')});
    pass('all three tenures, separate house shape, keyboard, one-decimal 만원 edits, precise interest and invalid-rate feedback');

    await page.locator('[name=salary]').fill('350');
    await page.locator('[name=externalAllowance]').fill('0');
    await page.locator('[name=startCash]').fill('1000');
    await page.locator('#custom-start-btn').click();
    current=await state();
    assert.equal(current.finance.cash,10000000,'existing principal is not newly paid into cash');
    assert.equal(current.finance.housingLoanPrincipal,100000000);
    assert.equal(current.finance.unpaidDebt,0);
    assert.equal(current.finance.debt,100000000);
    const auto=await page.locator('#auto-play').boundingBox();
    assert.ok(auto.y+auto.height<=844);
    await page.locator('#auto-play').click();
    await page.waitForFunction(()=>JSON.parse(render_game_to_text()).date>='2026-01-04',{},{timeout:7000});
    await page.locator('#auto-play').click();
    const first=await saved();assert.equal(first.ok,true,first.reason);
    const charge=first.state.finance.ledger.filter(l=>l.type==='fixed-cost');
    assert.equal(charge.length,1);
    assert.deepEqual({date:charge[0].date,rent:charge[0].rent,interest:charge[0].loanInterest,amount:charge[0].amount},
      {date:'2026-01-01',rent:751000,interest:364167,amount:2115167});
    await page.locator('#state-details>summary').click();
    assert.match(await page.locator('#finance-card').innerText(),/주거대출 이자/);
    assert.match(await page.locator('#finance-card').innerText(),/남은 주거대출 원금/);
    await page.locator('#finance-card').screenshot({path:path.join(output,'housing-monthly-finance.png')});
    await page.locator('#state-details>summary').click();
    await page.reload();
    await page.locator('#resume-game').click();
    assert.equal((await state()).automatic.active,false);
    assert.equal((await state()).housing.rateBps,437);
    assert.equal((await state()).housing.loanPrincipal,100000000);
    pass('January charges once, loan principal does not become cash and exact housing values survive browser resume');

    await page.locator('#auto-play').click();
    await page.waitForFunction(()=>JSON.parse(render_game_to_text()).mode==='finished',{},{timeout:120000});
    const annual=await saved();assert.equal(annual.ok,true,annual.reason);
    const charges=annual.state.finance.ledger.filter(l=>l.type==='fixed-cost');
    assert.equal(charges.length,12);
    assert.ok(charges.every(l=>l.date.endsWith('-01')&&l.rent===751000&&l.loanInterest===364167));
    current=await state();
    assert.equal(current.finance.housingRent,751000*12);
    assert.equal(current.finance.housingInterest,364167*12);
    assert.equal(current.finance.housingLoanPrincipal,100000000);
    assert.equal(current.finance.debt,current.finance.unpaidDebt+100000000);
    await page.locator('#year-details>summary').click();
    const table=page.locator('.financial-table');
    assert.match(await table.innerText(),/그중 월세/);
    assert.match(await table.innerText(),/그중 주거대출 이자/);
    assert.match(await table.innerText(),/미납·카드 청구 예정/);
    await table.screenshot({path:path.join(output,'housing-yearbook.png')});
    pass('real-timer year completion has twelve housing charges and separates annual rent, interest, principal and unpaid debt');

    const fixture=await page.evaluate(()=>{
      const config={...S2Data.PRESETS[0].config,housingTenure:'own',monthlyRent:0,housingLoanPrincipal:0,housingLoanRateBps:0,
        salary:3500000,externalAllowance:0,startCash:10000000,fixedCosts:1200000,preferences:['rest','read'],seed:2026};
      const s=S2Engine.create(config,'worker');S2Engine.advanceAutomatic(s);s.version=4;
      for(const key of ['housingTenure','monthlyRent','housingLoanPrincipal','housingLoanRateBps'])delete s.config[key];
      for(const entry of s.finance.ledger)if(entry.type==='fixed-cost')for(const key of ['livingCosts','rent','loanInterest','housingTenure','loanPrincipal','housingLoanRateBps'])delete entry[key];
      const payload=JSON.stringify(s);let checksum=2166136261;
      for(let i=0;i<payload.length;i++){checksum^=payload.charCodeAt(i);checksum=Math.imul(checksum,16777619);}
      const json=JSON.stringify({format:S2Storage.FORMAT,version:4,savedAt:new Date().toISOString(),checksum:(checksum>>>0).toString(16).padStart(8,'0'),state:s});
      const parsed=S2Storage.parse(json);if(parsed.ok)localStorage.setItem(S2Storage.KEY,json);
      return {ok:parsed.ok,reason:parsed.reason,date:s.date,cash:s.finance.cash};
    });
    assert.equal(fixture.ok,true,fixture.reason);
    await page.reload();await page.locator('#resume-game').click();
    current=await state();assert.equal(current.housing.tenure,'unspecified');assert.equal(current.housing.total,0);
    assert.equal(current.finance.cash,fixture.cash);
    await page.locator('#state-details>summary').click();
    assert.match(await page.locator('#finance-card').innerText(),/기존 고정비 · 주거비 포함/);
    assert.match(await page.locator('#finance-card').innerText(),/추가 주거비는 청구하지 않아요/);
    await page.locator('#finance-card').screenshot({path:path.join(output,'legacy-housing-finance.png')});
    await page.locator('#state-details>summary').click();
    await page.locator('#auto-play').click();
    await page.waitForFunction(()=>JSON.parse(render_game_to_text()).date>='2026-02-01',{},{timeout:20000});
    await page.locator('#auto-play').click();
    const legacy=(await saved()).state;
    const legacyCharges=legacy.finance.ledger.filter(l=>l.type==='fixed-cost');
    assert.equal(legacyCharges.length,2);assert.ok(legacyCharges.every(l=>l.amount===1200000));
    assert.equal((await state()).finance.housingCosts,0);assert.equal((await state()).finance.housingLoanPrincipal,0);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
    assert.equal((await state()).scene.reducedMotion,true);
    pass('v4 restore keeps original fixed costs and cash, adds no inferred housing debt and charges no extra rent next month');
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({checks,errors},null,2));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
